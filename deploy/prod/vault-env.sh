#!/usr/bin/env bash
# Runs ON THE VPS (called by deploy.sh). Renders the backend env file from Vault KV.
#   ./vault-env.sh <vault-env-file> <output-file>
#
# <vault-env-file> (root, chmod 600) defines:
#   VAULT_ADDR=http://127.0.0.1:8200
#   VAULT_ROLE_ID=...        VAULT_SECRET_ID=...      (AppRole, read-only policy)
#   VAULT_KV_PATH=kv/pnh/prod                         (<mount>/<path>; KV v1 or v2)
# Each key of the secret is written as KEY='value' (read verbatim by Compose env_file). On any error the output
# file is left untouched.
set -euo pipefail

REQUIRED=(PNH_DB_PASSWORD PNH_REDIS_PASSWORD PNH_MASTER_KEY)

CFG="${1:?usage: vault-env.sh <vault-env-file> <output-file>}"
OUT="${2:?usage: vault-env.sh <vault-env-file> <output-file>}"

die() { echo "vault-env: $*" >&2; exit 1; }

for bin in curl jq; do
  command -v "$bin" >/dev/null || die "$bin is required (apt install -y $bin)"
done
[[ -f "$CFG" ]] || die "$CFG not found"
mode="$(stat -c %a "$CFG" 2>/dev/null || stat -f %Lp "$CFG")"
[[ "$mode" == 600 ]] || die "$CFG must be mode 600 (is $mode)"

# shellcheck source=/dev/null
. "$CFG"
for v in VAULT_ADDR VAULT_ROLE_ID VAULT_SECRET_ID VAULT_KV_PATH; do
  [[ -n "${!v:-}" ]] || die "$v is not set in $CFG"
done
[[ "$VAULT_KV_PATH" == */* ]] || die "VAULT_KV_PATH must look like <mount>/<path> (got $VAULT_KV_PATH)"

TMP="$(mktemp -d)"
TOKEN_HDR="$TMP/token-header"   # token goes in a file, never on the command line
TMP_OUT=""
cleanup() {
  if [[ -f "$TOKEN_HDR" ]]; then
    curl -s -o /dev/null --max-time 5 -X POST -H "@$TOKEN_HDR" "$VAULT_ADDR/v1/auth/token/revoke-self" || true
  fi
  [[ -n "$TMP_OUT" ]] && rm -f "$TMP_OUT"
  rm -rf "$TMP"
}
trap cleanup EXIT

# vault_get PATH -> writes body to $TMP/body, prints HTTP status
vault_get() {
  curl -s -o "$TMP/body" -w '%{http_code}' --max-time 10 -H "@$TOKEN_HDR" "$VAULT_ADDR/v1/$1" || true
}

# 1. reachable + unsealed
status="$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 "$VAULT_ADDR/v1/sys/health" || true)"
case "$status" in
  000) die "cannot reach $VAULT_ADDR" ;;
  503) die "vault is sealed — unseal it, then deploy again" ;;
  501) die "vault is not initialized" ;;
  200 | 429 | 472 | 473) ;;
  *) die "unexpected health status $status from $VAULT_ADDR" ;;
esac

# 2. AppRole login (credentials sent on stdin)
status="$(jq -n --arg r "$VAULT_ROLE_ID" --arg s "$VAULT_SECRET_ID" '{role_id: $r, secret_id: $s}' |
  curl -s -o "$TMP/login" -w '%{http_code}' --max-time 10 --data @- "$VAULT_ADDR/v1/auth/approle/login" || true)"
[[ "$status" == 200 ]] || die "login failed (HTTP $status): $(jq -r '.errors | join("; ")' "$TMP/login" 2>/dev/null || true)"
printf 'X-Vault-Token: %s\n' "$(jq -r .auth.client_token "$TMP/login")" > "$TOKEN_HDR"
rm -f "$TMP/login"

# 3. read the secret: KV v2 first, then KV v1
mount="${VAULT_KV_PATH%%/*}"
path="${VAULT_KV_PATH#*/}"
if [[ "$(vault_get "$mount/data/$path")" == 200 ]] && jq -e '.data.data | type == "object"' "$TMP/body" >/dev/null; then
  jq '.data.data' "$TMP/body" > "$TMP/secret"
elif [[ "$(vault_get "$mount/$path")" == 200 ]] && jq -e '.data | type == "object"' "$TMP/body" >/dev/null; then
  jq '.data' "$TMP/body" > "$TMP/secret"
else
  die "no secret readable at $VAULT_KV_PATH (missing, deleted, or policy denies read)"
fi
rm -f "$TMP/body"

# 4. validate
bad="$(jq -r 'keys[] | select(test("^[A-Z_][A-Z0-9_]*$") | not)' "$TMP/secret")"
[[ -z "$bad" ]] || die "invalid key(s) (must match [A-Z_][A-Z0-9_]*): $(echo "$bad" | paste -sd, -)"
nl="$(jq -r 'to_entries[] | select(.value | tostring | test("[\r\n]")) | .key' "$TMP/secret")"
[[ -z "$nl" ]] || die "value contains a newline (not supported by env files): $(echo "$nl" | paste -sd, -)"
# values are written single-quoted (Compose reads them verbatim, \' = ') — a backslash at the end or
# right before a quote cannot be represented unambiguously
bs="$(jq -r --arg q "'" 'to_entries[] | select(.value | tostring | test("\\\\$") or contains("\\" + $q)) | .key' "$TMP/secret")"
[[ -z "$bs" ]] || die "value ends with a backslash or has a backslash before a quote: $(echo "$bs" | paste -sd, -)"
for k in "${REQUIRED[@]}"; do
  jq -e --arg k "$k" '(.[$k] // "") | tostring | length > 0' "$TMP/secret" >/dev/null || die "required key $k is missing or empty"
done

# 5. write atomically (mode 600)
TMP_OUT="$(mktemp "$OUT.tmp.XXXXXX")"
chmod 600 "$TMP_OUT"
{
  echo "# Generated by vault-env.sh from $VAULT_KV_PATH — do not edit, change the value in Vault"
  # KEY='value' — Compose's default env_file format would otherwise cut at " #", expand $VAR and strip quotes
  jq -r --arg q "'" 'to_entries | sort_by(.key)[] | "\(.key)=\($q)\(.value | tostring | gsub($q; "\\" + $q))\($q)"' "$TMP/secret"
} > "$TMP_OUT"
mv -f "$TMP_OUT" "$OUT"
TMP_OUT=""
echo "vault-env: wrote $(jq 'length' "$TMP/secret") keys from $VAULT_KV_PATH to $OUT"
